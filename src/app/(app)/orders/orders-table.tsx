"use client";

import { useMemo, useState } from "react";
import Link from "next/link";
import { Badge } from "@/components/ui/badge";
import { Table, TableHeader, TableBody, TableRow, TableHead, TableCell } from "@/components/ui/table";
import { formatCurrency } from "@/lib/utils";
import type { OrderStage, OrderStepKey } from "@/lib/order-workflow";
import { ackAiState, type AckAiState, type AckCheck, type AckFormState } from "@/lib/ack-form";
import { AckFormBadge, verifyAckFile, type AckFileRow } from "./ack-form-badge";
import { OrderStageActions } from "./order-stage-actions";

export interface OrderRow {
  id: string;
  quoteNumber: string;
  company: string;
  customerId: string;
  project: string;
  dateMs: number;
  dateText: string;
  currency: string;
  value: number;
  collected: number;
  balance: number;
  arrangement: string;
  status: string;
  sales: string;
  stage: OrderStage;
  stageText: string;
  prodDepts: string[];
  nextStep: OrderStepKey | null;
  nextLabel: string | null;
  canAct: boolean;
  blockedReason: string | null;
  awaiting: string | null;
  awaitingNames?: string[];
  /** Job Orders generated by the Engineer (per department), for the Purchaser view. */
  jobOrders: { number: string; dept: string }[];
  /** Acknowledgement Form uploaded (VAT-exclusive orders): signed, unsigned copy only, or none. */
  ackForm?: AckFormState;
  /** VAT-exclusive order — the only kind whose closing documents include an Acknowledgement Form. */
  nonVat?: boolean;
  /** Each Acknowledgement Form file, with the AI's verdict on it once checked. */
  ackFiles?: AckFileRow[];
  /** The AI's verdict over all of them. */
  ackAi?: AckAiState;
}

type DocFilter = "all" | "af" | "af_signed" | "af_missing" | "af_ai_flagged" | "af_ai_unchecked";
const DOC_FILTERS: { key: DocFilter; label: string }[] = [
  { key: "all", label: "All orders" },
  { key: "af", label: "Acknowledgement Form uploaded" },
  { key: "af_signed", label: "Acknowledgement Form — signed" },
  { key: "af_missing", label: "Acknowledgement Form — not yet" },
  { key: "af_ai_flagged", label: "Acknowledgement Form — AI says it isn't one" },
  { key: "af_ai_unchecked", label: "Acknowledgement Form — not checked by AI" },
];

type SortKey = "date" | "value" | "collected" | "balance" | "company" | "status" | "stage" | "sales";
type GroupKey = "none" | "status" | "stage" | "sales" | "company" | "arrangement";

const SORT_OPTIONS: { key: SortKey; label: string }[] = [
  { key: "date", label: "Date" },
  { key: "value", label: "Value" },
  { key: "collected", label: "Collected" },
  { key: "balance", label: "Balance" },
  { key: "company", label: "Client" },
  { key: "status", label: "Status" },
  { key: "stage", label: "Order stage" },
  { key: "sales", label: "Sales" },
];
const GROUP_OPTIONS: { key: GroupKey; label: string }[] = [
  { key: "none", label: "No grouping" },
  { key: "status", label: "Status" },
  { key: "stage", label: "Order stage" },
  { key: "sales", label: "Sales" },
  { key: "company", label: "Client" },
  { key: "arrangement", label: "Terms" },
];

const statusVariant = (s: string): "success" | "warning" | "secondary" => (s === "Paid" ? "success" : s === "Partial" ? "warning" : "secondary");

export function OrdersTable({
  orders,
  progressHidden,
  restricted = false,
  isPurchaser = false,
  initialStage,
  initialStageLabel,
  initialDept,
  initialDeptLabel,
  canVerifyAck = false,
}: {
  orders: OrderRow[];
  progressHidden: boolean;
  restricted?: boolean;
  /** Purchaser view: hide Value/Collected/Balance, show a Job Orders column instead. */
  isPurchaser?: boolean;
  initialStage?: string;
  initialStageLabel?: string;
  initialDept?: string;
  initialDeptLabel?: string;
  /** Accounting / Payment Approver / admin: may run the AI Acknowledgement Form check. */
  canVerifyAck?: boolean;
}) {
  const [sortKey, setSortKey] = useState<SortKey>("date");
  const [dir, setDir] = useState<"asc" | "desc">("desc");
  const [group, setGroup] = useState<GroupKey>("none");
  const [query, setQuery] = useState("");
  const [docFilter, setDocFilter] = useState<DocFilter>("all");
  // AI verdicts made on this page, ahead of the next server refresh.
  const [freshChecks, setFreshChecks] = useState<Record<string, AckCheck>>({});
  const onChecked = (path: string, check: AckCheck) => setFreshChecks((m) => ({ ...m, [path]: check }));
  const [bulk, setBulk] = useState<{ done: number; total: number; failed: number; error: string | null } | null>(null);
  const withChecks = useMemo(() => {
    if (Object.keys(freshChecks).length === 0) return orders;
    return orders.map((o) => {
      if (!o.ackFiles?.some((f) => freshChecks[f.path])) return o;
      const ackFiles = o.ackFiles.map((f) => ({ ...f, check: freshChecks[f.path] ?? f.check }));
      const checks = Object.fromEntries(ackFiles.filter((f) => f.check).map((f) => [f.path, f.check!]));
      return { ...o, ackFiles, ackAi: ackAiState(ackFiles, checks) };
    });
  }, [orders, freshChecks]);
  // Purchaser view collapses Value/Collected/Balance (3 cols) into one Job Orders col.
  const colSpan = isPurchaser ? 8 : 10;

  // A drill-down filter from the Management dashboard (a stage or a department).
  const filterLabel = initialStageLabel ?? initialDeptLabel ?? null;
  const base = useMemo(() => {
    return withChecks.filter((o) => {
      if (initialStage && o.stage !== initialStage) return false;
      if (initialDept && !o.prodDepts.includes(initialDept)) return false;
      if (docFilter === "af" && !o.ackForm) return false;
      if (docFilter === "af_signed" && o.ackForm !== "signed") return false;
      // "Not yet" = VAT-exclusive orders (the only ones with an Acknowledgement
      // Form) still without one. `ackForm` is null for both, so look at the terms.
      if (docFilter === "af_missing" && (o.ackForm || !o.nonVat)) return false;
      if (docFilter === "af_ai_flagged" && o.ackAi !== "flagged") return false;
      if (docFilter === "af_ai_unchecked" && o.ackAi !== "unchecked" && o.ackAi !== "unclear") return false;
      return true;
    });
  }, [withChecks, initialStage, initialDept, docFilter]);

  // Every Acknowledgement Form file in view the AI hasn't settled yet.
  const unchecked = useMemo(
    () => base.flatMap((o) => (o.ackFiles ?? []).filter((f) => !f.check || f.check.verdict === "unclear").map((f) => ({ orderId: o.id, path: f.path }))),
    [base],
  );
  async function checkAll() {
    const todo = unchecked;
    if (!todo.length) return;
    if (!window.confirm(`Ask the AI to check ${todo.length} Acknowledgement Form file${todo.length === 1 ? "" : "s"}? Each is one AI read.`)) return;
    setBulk({ done: 0, total: todo.length, failed: 0, error: null });
    let failed = 0;
    let error: string | null = null;
    for (let i = 0; i < todo.length; i++) {
      try {
        onChecked(todo[i].path, await verifyAckFile(todo[i].orderId, todo[i].path));
      } catch (e) {
        failed += 1;
        error = e instanceof Error ? e.message : "The check failed.";
      }
      setBulk({ done: i + 1, total: todo.length, failed, error });
    }
  }

  // Search across order no., client (company + project), date, and sales.
  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return base;
    // Order-number match ignores every separator (spaces, hyphens, en/em dashes,
    // slashes…), so "2026 - AFBM0012", "2026-AFBM0012" and "2026afbm0012" all find
    // the same order regardless of how the number was punctuated.
    const compact = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/gi, "");
    const qCompact = compact(q);
    return base.filter((o) => {
      if ([o.quoteNumber, o.company, o.project, o.dateText, o.sales].some((f) => (f ?? "").toLowerCase().includes(q))) return true;
      return qCompact.length > 0 && compact(o.quoteNumber ?? "").includes(qCompact);
    });
  }, [base, query]);

  const groupValue = (o: OrderRow): string => {
    switch (group) {
      case "status": return o.status;
      case "stage": return o.stageText;
      case "sales": return o.sales || "—";
      case "company": return o.company;
      case "arrangement": return o.arrangement || "—";
      default: return "";
    }
  };

  const sorted = useMemo(() => {
    const mul = dir === "asc" ? 1 : -1;
    const cmp = (a: OrderRow, b: OrderRow): number => {
      switch (sortKey) {
        case "value": return (a.value - b.value) * mul;
        case "collected": return (a.collected - b.collected) * mul;
        case "balance": return (a.balance - b.balance) * mul;
        case "company": return a.company.localeCompare(b.company) * mul;
        case "status": return a.status.localeCompare(b.status) * mul;
        case "stage": return a.stageText.localeCompare(b.stageText) * mul;
        case "sales": return (a.sales || "").localeCompare(b.sales || "") * mul;
        default: return (a.dateMs - b.dateMs) * mul;
      }
    };
    return [...filtered].sort(cmp);
  }, [filtered, sortKey, dir]);

  // Build groups (in first-appearance order of the sorted rows).
  const groups = useMemo(() => {
    if (group === "none") return [{ key: "", rows: sorted }];
    const map = new Map<string, OrderRow[]>();
    for (const o of sorted) {
      const k = groupValue(o);
      (map.get(k) ?? map.set(k, []).get(k)!).push(o);
    }
    return [...map.entries()].map(([key, rows]) => ({ key, rows }));
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [sorted, group]);

  const currency = orders[0]?.currency ?? "PHP";

  return (
    <div className="space-y-3">
      {filterLabel && (
        <div className="flex flex-wrap items-center gap-2">
          <span className="text-xs text-muted-foreground">Showing orders in</span>
          <span className="inline-flex items-center gap-1.5 rounded-full border bg-primary/5 px-2.5 py-1 text-xs font-medium text-primary">
            {initialStageLabel ? "Stage" : "Department"}: {filterLabel}
            <Link href="/orders" className="ml-0.5 rounded-full text-primary/70 hover:text-primary" aria-label="Clear filter" title="Clear filter">✕</Link>
          </span>
          <span className="text-xs text-muted-foreground">{base.length} order{base.length === 1 ? "" : "s"}</span>
        </div>
      )}
      <div className="flex flex-wrap items-center gap-3">
        <div className="relative">
          <input
            type="search"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search order, client, date, sales…"
            className="h-8 w-64 rounded-md border bg-background px-3 text-sm"
          />
        </div>
        <label className="flex items-center gap-1.5 text-xs text-muted-foreground">
          Group by
          <select value={group} onChange={(e) => setGroup(e.target.value as GroupKey)} className="h-8 rounded-md border bg-background px-2 text-sm text-foreground">
            {GROUP_OPTIONS.map((g) => <option key={g.key} value={g.key}>{g.label}</option>)}
          </select>
        </label>
        <label className="flex items-center gap-1.5 text-xs text-muted-foreground">
          Sort by
          <select value={sortKey} onChange={(e) => setSortKey(e.target.value as SortKey)} className="h-8 rounded-md border bg-background px-2 text-sm text-foreground">
            {SORT_OPTIONS.map((s) => <option key={s.key} value={s.key}>{s.label}</option>)}
          </select>
        </label>
        <label className="flex items-center gap-1.5 text-xs text-muted-foreground">
          Documents
          <select value={docFilter} onChange={(e) => setDocFilter(e.target.value as DocFilter)} className="h-8 rounded-md border bg-background px-2 text-sm text-foreground">
            {DOC_FILTERS.map((f) => <option key={f.key} value={f.key}>{f.label}</option>)}
          </select>
        </label>
        <button
          type="button"
          onClick={() => setDir((d) => (d === "asc" ? "desc" : "asc"))}
          className="inline-flex h-8 items-center gap-1 rounded-md border bg-background px-2.5 text-sm hover:bg-accent"
          title={dir === "asc" ? "Ascending" : "Descending"}
        >
          {dir === "asc" ? "↑ Asc" : "↓ Desc"}
        </button>
        {docFilter !== "all" && (
          <span className="text-xs text-muted-foreground">{base.length} order{base.length === 1 ? "" : "s"}</span>
        )}
        {canVerifyAck && docFilter.startsWith("af") && docFilter !== "af_missing" && unchecked.length > 0 && !(bulk && bulk.done < bulk.total) && (
          <button type="button" onClick={checkAll} className="inline-flex h-8 items-center rounded-md border border-primary/40 bg-primary/5 px-2.5 text-xs font-medium text-primary hover:bg-primary/10">
            ✨ Check {unchecked.length} file{unchecked.length === 1 ? "" : "s"} with AI
          </button>
        )}
        {bulk && (
          <span className="text-xs text-muted-foreground">
            {bulk.done < bulk.total ? `Checking ${bulk.done + 1} of ${bulk.total}…` : `Checked ${bulk.total - bulk.failed} of ${bulk.total}`}
            {bulk.failed > 0 && <span className="text-destructive"> · {bulk.failed} failed{bulk.error ? ` — ${bulk.error}` : ""}</span>}
          </span>
        )}
      </div>

      <div className="overflow-x-auto">
        <Table>
          <TableHeader>
            <TableRow>
              <TableHead>Order</TableHead>
              <TableHead>Client</TableHead>
              <TableHead>Date</TableHead>
              <TableHead>Terms</TableHead>
              {isPurchaser ? (
                <TableHead>Job Orders</TableHead>
              ) : (
                <>
                  <TableHead className="text-right">Value</TableHead>
                  <TableHead className="text-right">Collected</TableHead>
                  <TableHead className="text-right">Balance</TableHead>
                </>
              )}
              <TableHead>Status</TableHead>
              <TableHead>Order stage</TableHead>
              <TableHead>Sales</TableHead>
            </TableRow>
          </TableHeader>
          <TableBody>
            {sorted.length === 0 ? (
              <TableRow>
                <TableCell colSpan={colSpan} className="py-8 text-center text-sm text-muted-foreground">
                  {docFilter !== "all" && !query ? `No orders — ${DOC_FILTERS.find((f) => f.key === docFilter)?.label ?? "filter"}.` : query ? <>No orders match &ldquo;{query}&rdquo;{filterLabel ? ` in ${filterLabel}` : ""}.</> : filterLabel ? `No orders in ${filterLabel} right now.` : "No orders."}
                </TableCell>
              </TableRow>
            ) : (
              groups.map((g) => (
                <GroupRows key={g.key} groupKey={g.key} rows={g.rows} showHeader={group !== "none"} currency={currency} progressHidden={progressHidden} restricted={restricted} isPurchaser={isPurchaser} colSpan={colSpan} canVerifyAck={canVerifyAck} onChecked={onChecked} />
              ))
            )}
          </TableBody>
        </Table>
      </div>
    </div>
  );
}

function GroupRows({ groupKey, rows, showHeader, currency, progressHidden, restricted, isPurchaser, colSpan, canVerifyAck, onChecked }: { groupKey: string; rows: OrderRow[]; showHeader: boolean; currency: string; progressHidden: boolean; restricted: boolean; isPurchaser: boolean; colSpan: number; canVerifyAck: boolean; onChecked: (path: string, check: AckCheck) => void }) {
  const total = rows.reduce((a, o) => a + o.value, 0);
  return (
    <>
      {showHeader && (
        <TableRow className="bg-muted/40">
          <TableCell colSpan={colSpan} className="py-1.5">
            <span className="text-sm font-semibold">{groupKey || "—"}</span>
            <span className="ml-2 text-xs text-muted-foreground">{rows.length} order{rows.length === 1 ? "" : "s"}{restricted ? "" : ` · ${formatCurrency(total, currency)}`}</span>
          </TableCell>
        </TableRow>
      )}
      {rows.map((o) => (
        <TableRow key={o.id}>
          <TableCell>
            <Link href={`/quotations/${o.id}`} className="font-medium text-primary hover:underline">{o.quoteNumber}</Link>
            {o.ackForm && (
              <AckFormBadge orderId={o.id} state={o.ackForm} ai={o.ackAi ?? null} files={o.ackFiles ?? []} canVerify={canVerifyAck} onChecked={onChecked} />
            )}
          </TableCell>
          <TableCell>
            {restricted ? (
              <span className="text-muted-foreground">{o.company}</span>
            ) : (
              <Link href={`/customers/${o.customerId}`} className="font-medium text-primary hover:underline">{o.company}</Link>
            )}
            {!restricted && o.project && <div className="text-xs text-muted-foreground">{o.project}</div>}
          </TableCell>
          <TableCell className="whitespace-nowrap text-sm">{o.dateText}</TableCell>
          <TableCell className="text-xs text-muted-foreground">{o.arrangement}</TableCell>
          {isPurchaser ? (
            <TableCell>
              {o.jobOrders.length === 0 ? (
                <span className="text-muted-foreground">—</span>
              ) : (
                <div className="flex flex-wrap gap-x-2 gap-y-0.5">
                  {o.jobOrders.map((jo) => (
                    <Link
                      key={`${jo.dept}-${jo.number}`}
                      href={`/orders/${o.id}`}
                      title={`${jo.dept} job order — open the JO workflow`}
                      className="font-mono text-sm font-medium text-primary hover:underline"
                    >
                      {jo.number}
                    </Link>
                  ))}
                </div>
              )}
            </TableCell>
          ) : (
            <>
              <TableCell className="text-right tabular-nums">{restricted ? "—" : formatCurrency(o.value, o.currency)}</TableCell>
              <TableCell className="text-right tabular-nums">{restricted ? "—" : formatCurrency(o.collected, o.currency)}</TableCell>
              <TableCell className="text-right tabular-nums">{restricted ? "—" : formatCurrency(o.balance, o.currency)}</TableCell>
            </>
          )}
          <TableCell><Badge variant={statusVariant(o.status)}>{o.status}</Badge></TableCell>
          <TableCell>
            <OrderStageActions
              orderId={o.id}
              stage={o.stage}
              stageLabel={o.stageText}
              nextStep={o.nextStep}
              nextLabel={o.nextLabel}
              canAct={o.canAct}
              blockedReason={o.blockedReason}
              awaiting={o.awaiting}
              awaitingNames={o.awaitingNames}
              hideStage={progressHidden}
            />
          </TableCell>
          <TableCell className="text-sm text-muted-foreground">{o.sales}</TableCell>
        </TableRow>
      ))}
    </>
  );
}
